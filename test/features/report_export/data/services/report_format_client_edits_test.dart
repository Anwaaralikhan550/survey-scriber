// Client edits 2 Nov 2026 ("Survey Scriber Edit Oct 2026.docx"): the report layout, checked
// on the Word file itself. The PDF renderer's text streams are compressed, so PDF
// output is compared with the client's pictures by eye.
import 'dart:convert';
import 'dart:io';

import 'package:archive/archive.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path_provider_platform_interface/path_provider_platform_interface.dart';
import 'package:survey_scriber/features/report_export/data/services/docx_generator_service.dart';
import 'package:survey_scriber/features/report_export/domain/models/export_config.dart';
import 'package:survey_scriber/features/report_export/domain/models/report_document.dart';

class _Paths extends PathProviderPlatform {
  _Paths(this.docs);
  final String docs;
  @override
  Future<String?> getApplicationDocumentsPath() async => docs;
}

ReportDocument _doc({
  ReportType type = ReportType.inspection,
  List<ReportSection>? sections,
}) =>
    ReportDocument(
      reportType: type,
      title: 'Inspection - ref-354',
      generatedAt: DateTime(2026, 11, 2, 12, 29),
      surveyMeta: SurveyMeta(
        surveyId: 's1',
        title: 'Inspection - ref-354',
        address: 'abc street',
        jobRef: 'ref-354',
        clientName: 'jahanzaib',
        inspectionDate: DateTime(2026, 2, 28),
        surveyDuration: const Duration(hours: 6, minutes: 3),
      ),
      sections: sections ??
          const [
            ReportSection(
              key: 'A',
              title: 'About Inspection',
              description: '',
              displayOrder: 0,
              screens: [],
            ),
          ],
    );

Future<String> _xml(ReportDocument doc, [String part = 'word/document.xml']) async {
  final result = await DocxGeneratorService(const ExportConfig()).generateDocx(doc);
  final file = ZipDecoder().decodeBytes(result.bytes).findFile(part)!;
  return utf8.decode(file.content as List<int>);
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  PathProviderPlatform.instance =
      _Paths(Directory.systemTemp.createTempSync('docx_format_').path);

  group('first page', () {
    test('banner and details table as in the client picture', () async {
      final xml = await _xml(_doc());
      expect(xml, contains('RICS HomeBuyer Report'));
      expect(xml, contains('Level 2 Home Survey'));
      expect(xml, isNot(contains('Home Survey Inspection Report')));
      expect(xml, contains('w:fill="1461BF"'));
      final order = ['Property Address', 'Client Name', 'Job Reference', 'Inspection Date',
        'Report Generated', 'Survey Duration'];
      var at = 0;
      for (final label in order) {
        final i = xml.indexOf(label, at);
        expect(i, greaterThan(-1), reason: label);
        at = i;
      }
      expect(xml, contains('28 February 2026'));
      expect(xml, contains('6h 03m'));
      expect(xml, isNot(contains('Prepared by:')));
    });

    test('valuation first page is left alone', () async {
      final xml = await _xml(_doc(type: ReportType.valuation));
      expect(xml, contains('Valuation Report'));
      expect(xml, contains('Prepared by:'));
      expect(xml, isNot(contains('RICS HomeBuyer Report')));
    });
  });

  group('section layout', () {
    const sections = [
      ReportSection(key: 'A', title: 'About Inspection', description: '', displayOrder: 0, screens: []),
      ReportSection(
        key: 'E',
        title: 'Outside Property',
        description: '',
        displayOrder: 1,
        screens: [
          ReportScreen(screenId: 's', title: 'Stacks', fields: [], phrases: ['Some text.']),
        ],
      ),
    ];

    test('coloured banner with white bold text, sub-headers bold dark', () async {
      final xml = await _xml(_doc(sections: sections));
      final at = xml.indexOf('Outside Property');
      final banner = xml.substring(xml.lastIndexOf('<w:tbl>', at), at);
      expect(banner, contains('w:fill="2E7D33"'));
      expect(banner, contains('<w:b/><w:color w:val="FFFFFF"/>'));
      final styles = await _xml(_doc(sections: sections), 'word/styles.xml');
      expect(styles, contains('w:ascii="Noto Sans"'));
      expect(styles, contains('<w:color w:val="333333"/>'));
    });

    test('running header and footer, not on the first page', () async {
      final doc = _doc(sections: sections);
      final xml = await _xml(doc);
      expect(xml, contains('<w:titlePg/>'));
      expect(xml, contains('r:id="rIdHeader1"'));
      final header = await _xml(doc, 'word/header1.xml');
      expect(header, contains('RICS HomeBuyer Report'));
      expect(header, contains('Inspection - ref-354'));
      final footer = await _xml(doc, 'word/footer1.xml');
      expect(footer, contains('Generated by SurveyScriber'));
      expect(footer, contains('NUMPAGES'));
      expect(await _xml(doc, '[Content_Types].xml'), contains('/word/header1.xml'));
      expect(await _xml(doc, 'word/_rels/document.xml.rels'), contains('header1.xml'));
    });

    test('valuation keeps its plain headings and Calibri', () async {
      final doc = _doc(type: ReportType.valuation, sections: sections);
      final xml = await _xml(doc);
      expect(xml, isNot(contains('<w:titlePg/>')));
      expect(xml, isNot(contains('w:fill="2E7D33"')));
      expect(await _xml(doc, 'word/styles.xml'), contains('w:ascii="Calibri"'));
    });
  });

  test('every main section starts on a new page, the first one follows the cover', () async {
    const sections = [
      ReportSection(key: 'A', title: 'About Inspection', description: '', displayOrder: 0, screens: []),
      ReportSection(key: 'D', title: 'About Property', description: '', displayOrder: 1, screens: []),
      ReportSection(key: 'E', title: 'Outside Property', description: '', displayOrder: 2, screens: []),
    ];
    final xml = await _xml(_doc(sections: sections));
    expect('<w:pageBreakBefore/>'.allMatches(xml), hasLength(2));
    expect(xml.indexOf('<w:pageBreakBefore/>'), greaterThan(xml.indexOf('About Inspection')));
    expect(xml.indexOf('<w:pageBreakBefore/>'), lessThan(xml.indexOf('About Property')));
  });

  test('condition rating line is bold, its explanation is not', () async {
    const sections = [
      ReportSection(
        key: 'E',
        title: 'Outside Property',
        description: '',
        displayOrder: 0,
        screens: [
          ReportScreen(screenId: 's', title: 'Stacks', fields: [], phrases: [
            'Condition rating is: 1.',
            'The element(s) are performing their intended function.',
          ],),
        ],
      ),
    ];
    final xml = await _xml(_doc(sections: sections));
    expect(xml, contains('<w:b/></w:rPr><w:t xml:space="preserve">Condition rating is: 1.</w:t>'));
    expect(xml, contains('<w:r><w:t xml:space="preserve">The element(s) are performing'));
  });
}
