// Client edits 2 Nov 2026 ("Survey Scriber Edit Oct 2026.docx"): the report layout, checked
// on the Word file itself. The PDF renderer's text streams are compressed, so PDF
// output is compared with the client's pictures by eye.
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:archive/archive.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path_provider_platform_interface/path_provider_platform_interface.dart';
import 'package:survey_scriber/features/report_export/data/services/docx_generator_service.dart';
import 'package:survey_scriber/features/report_export/domain/models/export_config.dart';
import 'package:survey_scriber/features/report_export/domain/models/report_document.dart';

class _Paths extends PathProviderPlatform {
  _Paths(this.docs);
  final String docs;
  @override
  Future<String?> getApplicationDocumentsPath() async => docs;
}

/// A PNG header is all the Word generator reads for the logo's shape.
Uint8List _png(int width, int height) {
  final bytes = ByteData(24)
    ..setUint32(0, 0x89504E47)
    ..setUint32(16, width)
    ..setUint32(20, height);
  return bytes.buffer.asUint8List();
}

ReportDocument _doc({
  ReportType type = ReportType.inspection,
  List<ReportSection>? sections,
}) =>
    ReportDocument(
      reportType: type,
      title: 'Inspection - ref-354',
      generatedAt: DateTime(2026, 11, 2, 12, 29),
      surveyMeta: SurveyMeta(
        surveyId: 's1',
        title: 'Inspection - ref-354',
        address: 'abc street',
        jobRef: 'ref-354',
        clientName: 'jahanzaib',
        inspectionDate: DateTime(2026, 2, 28),
        surveyDuration: const Duration(hours: 6, minutes: 3),
      ),
      sections: sections ??
          const [
            ReportSection(
              key: 'A',
              title: 'About Inspection',
              description: '',
              displayOrder: 0,
              screens: [],
            ),
          ],
    );

Future<String> _xml(
  ReportDocument doc, [
  String part = 'word/document.xml',
  ExportConfig config = const ExportConfig(),
]) async {
  final result = await DocxGeneratorService(config).generateDocx(doc);
  final file = ZipDecoder().decodeBytes(result.bytes).findFile(part)!;
  return utf8.decode(file.content as List<int>);
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  PathProviderPlatform.instance =
      _Paths(Directory.systemTemp.createTempSync('docx_format_').path);

  group('first page', () {
    test('banner and details table as in the client picture', () async {
      final xml = await _xml(_doc());
      expect(xml, contains('Home Buyer Report'));
      expect(xml, contains('Level 2 Home Survey'));
      expect(xml, isNot(contains('RICS')));
      expect(xml, isNot(contains('Home Survey Inspection Report')));
      expect(xml, contains('w:fill="1461BF"'));
      final order = ['Property Address', 'Client Name', 'Job Reference', 'Inspection Date',
        'Report Generated', 'Survey Duration'];
      var at = 0;
      for (final label in order) {
        final i = xml.indexOf(label, at);
        expect(i, greaterThan(-1), reason: label);
        at = i;
      }
      expect(xml, contains('28 February 2026'));
      expect(xml, contains('6h 03m'));
      expect(xml, isNot(contains('Prepared by:')));
    });

    test('valuation first page has the same bar and table as its PDF', () async {
      final xml = await _xml(_doc(type: ReportType.valuation));
      expect(xml, contains('Valuation Report'));
      expect(xml, contains('Mortgage Valuation Report'));
      expect(xml, contains('w:fill="1461BF"'));
      expect(xml, contains('Property Address'));
      expect(xml, contains('Report Generated'));
      expect(xml, isNot(contains('Prepared by:')));
      expect(xml, isNot(contains('Home Buyer Report')));
      expect(xml, isNot(contains('Level 2')));
    });

    test('valuation header and footer: its own name, the company in the footer', () async {
      const config = ExportConfig(reportCompanyName: 'Francis Blackstone Surveyor');
      final doc = _doc(type: ReportType.valuation);
      final header = await _xml(doc, 'word/header1.xml', config);
      expect(header, contains('Property Valuation Report'));
      expect(header, isNot(contains('Level 2')));
      final footer = await _xml(doc, 'word/footer1.xml', config);
      final company = footer.indexOf('Francis Blackstone Surveyor');
      expect(company, greaterThan(footer.indexOf('Generated by SurveyScriber')));
      expect(company, lessThan(footer.indexOf('PAGE')));
      expect(await _xml(doc, 'word/document.xml', config), contains('<w:titlePg/>'));
    });

    test('company name is the first of three rows', () async {
      final xml = await _xml(
        _doc(),
        'word/document.xml',
        const ExportConfig(reportCompanyName: 'Francis Blackstone Surveyor'),
      );
      final rows = ['Francis Blackstone Surveyor', 'Home Buyer Report', 'Level 2 Home Survey'];
      var at = 0;
      for (final row in rows) {
        at = xml.indexOf(row, at);
        expect(at, greaterThan(-1), reason: row);
      }
      expect(xml, isNot(contains('<w:drawing>')));
    });

    test('logo floats at the left end of the bar, in its own shape', () async {
      final config = ExportConfig(
        reportCompanyName: 'Francis Blackstone Surveyor',
        reportCompanyLogo: _png(400, 100),
      );
      final xml = await _xml(_doc(), 'word/document.xml', config);
      expect(xml.indexOf('<w:drawing>'), lessThan(xml.indexOf('Francis Blackstone Surveyor')));
      expect(xml, contains('<wp:extent cx="740000" cy="185000"/>'));
      expect(xml, contains('<wp:anchor '));
      expect(xml, contains('<wp:wrapNone/>'));
      expect(xml, contains('<w:ind w:left="1340" w:right="1340"/>'));
      final rels = await _xml(_doc(), 'word/_rels/document.xml.rels', config);
      expect(rels, contains('media/image1.png'));
      expect(await _xml(_doc(), '[Content_Types].xml', config), contains('image/png'));
    });

    test('valuation shows the saved company and logo', () async {
      final xml = await _xml(
        _doc(type: ReportType.valuation),
        'word/document.xml',
        ExportConfig(reportCompanyName: 'Francis Blackstone', reportCompanyLogo: _png(100, 100)),
      );
      expect(xml, contains('Francis Blackstone'));
      expect(xml, contains('<wp:anchor '));
      expect(xml.indexOf('<w:drawing>'), lessThan(xml.indexOf('Valuation Report')));
    });
  });

  group('section layout', () {
    const sections = [
      ReportSection(key: 'A', title: 'About Inspection', description: '', displayOrder: 0, screens: []),
      ReportSection(
        key: 'E',
        title: 'Outside Property',
        description: '',
        displayOrder: 1,
        screens: [
          ReportScreen(screenId: 's', title: 'Stacks', fields: [], phrases: ['Some text.']),
        ],
      ),
    ];

    test('coloured banner with white bold text, sub-headers bold dark', () async {
      final xml = await _xml(_doc(sections: sections));
      final at = xml.indexOf('Outside Property');
      final banner = xml.substring(xml.lastIndexOf('<w:tbl>', at), at);
      expect(banner, contains('w:fill="2E7D33"'));
      expect(banner, contains('<w:b/><w:color w:val="FFFFFF"/>'));
      final styles = await _xml(_doc(sections: sections), 'word/styles.xml');
      expect(styles, contains('w:ascii="Noto Sans"'));
      expect(styles, contains('<w:color w:val="333333"/>'));
    });

    test('running header and footer, not on the first page', () async {
      final doc = _doc(sections: sections);
      final xml = await _xml(doc);
      expect(xml, contains('<w:titlePg/>'));
      expect(xml, contains('r:id="rIdHeader1"'));
      final header = await _xml(doc, 'word/header1.xml');
      expect(header, contains('Level 2 Home Survey Report'));
      expect(header, isNot(contains('RICS')));
      expect(header, contains('Inspection - ref-354'));
      final footer = await _xml(doc, 'word/footer1.xml');
      expect(footer, contains('Generated by SurveyScriber'));
      expect(footer, contains('NUMPAGES'));
      expect(await _xml(doc, '[Content_Types].xml'), contains('/word/header1.xml'));
      expect(await _xml(doc, 'word/_rels/document.xml.rels'), contains('header1.xml'));
    });

    test('footer: company name sits between Generated by and the page number', () async {
      final footer = await _xml(
        _doc(sections: sections),
        'word/footer1.xml',
        const ExportConfig(reportCompanyName: 'Francis Blackstone Surveyor'),
      );
      final company = footer.indexOf('Francis Blackstone Surveyor');
      expect(company, greaterThan(footer.indexOf('Generated by SurveyScriber')));
      expect(company, lessThan(footer.indexOf('PAGE')));
    });

    test('valuation keeps its plain headings and Calibri', () async {
      final doc = _doc(type: ReportType.valuation, sections: sections);
      final xml = await _xml(doc);
      expect(xml, isNot(contains('w:fill="2E7D33"')));
      expect(await _xml(doc, 'word/styles.xml'), contains('w:ascii="Calibri"'));
    });
  });

  test('every main section starts on a new page, the first one follows the cover', () async {
    const sections = [
      ReportSection(key: 'A', title: 'About Inspection', description: '', displayOrder: 0, screens: []),
      ReportSection(key: 'D', title: 'About Property', description: '', displayOrder: 1, screens: []),
      ReportSection(key: 'E', title: 'Outside Property', description: '', displayOrder: 2, screens: []),
    ];
    final xml = await _xml(_doc(sections: sections));
    expect('<w:pageBreakBefore/>'.allMatches(xml), hasLength(2));
    expect(xml.indexOf('<w:pageBreakBefore/>'), greaterThan(xml.indexOf('About Inspection')));
    expect(xml.indexOf('<w:pageBreakBefore/>'), lessThan(xml.indexOf('About Property')));
  });

  test('condition rating line is bold, its explanation is not', () async {
    const sections = [
      ReportSection(
        key: 'E',
        title: 'Outside Property',
        description: '',
        displayOrder: 0,
        screens: [
          ReportScreen(screenId: 's', title: 'Stacks', fields: [], phrases: [
            'Condition rating is: 1.',
            'The element(s) are performing their intended function.',
          ],),
        ],
      ),
    ];
    final xml = await _xml(_doc(sections: sections));
    expect(xml, contains('<w:b/></w:rPr><w:t xml:space="preserve">Condition rating is: 1.</w:t>'));
    expect(xml, contains('<w:r><w:t xml:space="preserve">The element(s) are performing'));
  });

  group('colour side bar', () {
    ReportSection section(String key, String title) => ReportSection(
          key: key,
          title: title,
          description: '',
          displayOrder: 0,
          screens: const [
            ReportScreen(
              screenId: 'g',
              title: 'Chimney Stacks',
              fields: [],
              isMergedGroup: true,
              phrases: ['Condition rating is: 1.', 'Body paragraph.'],
            ),
          ],
        );

    const bar = '<w:pBdr><w:left w:val="single" w:sz="24" w:space="4" w:color="2E7D33"/></w:pBdr>';

    test('heading and rating share the section colour, the text below has none', () async {
      final xml = await _xml(_doc(sections: [section('E', 'Outside Property')]));
      expect(bar.allMatches(xml), hasLength(2));
      expect(xml.indexOf(bar), lessThan(xml.indexOf('Chimney Stacks')));
      expect(xml.lastIndexOf(bar), lessThan(xml.indexOf('Condition rating is: 1.')));
      expect(xml.lastIndexOf(bar), greaterThan(xml.indexOf('Chimney Stacks')));
      final body = xml.indexOf('Body paragraph.');
      expect(xml.substring(xml.lastIndexOf('<w:p>', body), body), isNot(contains('w:pBdr')));
    });

    test('runs from Outside Property to Risks only', () async {
      for (final key in ['E', 'H', 'F', 'G', 'I', 'J']) {
        final xml = await _xml(_doc(sections: [section(key, 'S')]));
        expect(xml, contains('<w:left w:val="single" w:sz="24"'), reason: key);
      }
      for (final key in ['A', 'D', 'K']) {
        final xml = await _xml(_doc(sections: [section(key, 'S')]));
        expect(xml, isNot(contains('w:sz="24" w:space="4"')), reason: key);
      }
    });

    test('valuation has none', () async {
      final xml = await _xml(_doc(
        type: ReportType.valuation,
        sections: [section('E', 'Outside Property')],
      ));
      expect(xml, isNot(contains('w:sz="24" w:space="4"')));
    });
  });

  test('I Issues: the words before the dash print bold', () async {
    ReportSection issues(String key) => ReportSection(
          key: key,
          title: 'S',
          description: '',
          displayOrder: 0,
          screens: const [
            ReportScreen(
              screenId: 's',
              title: 'I1 Regulation',
              fields: [],
              phrases: ['Gas Installation \u2013 Whether recent gas safety records exist.'],
            ),
          ],
        );
    final xml = await _xml(_doc(sections: [issues('I')]));
    expect(xml, contains('<w:b/></w:rPr><w:t xml:space="preserve">Gas Installation</w:t>'));
    expect(xml, contains('\u2013 Whether recent gas safety records exist.'));
    expect(await _xml(_doc(sections: [issues('G')])),
        isNot(contains('<w:b/></w:rPr><w:t xml:space="preserve">Gas Installation</w:t>')));
  });

  test('sub-heading marker never prints; a sub-heading with no text is dropped', () async {
    const sections = [
      ReportSection(
        key: 'H',
        title: 'H Grounds',
        description: '',
        displayOrder: 0,
        screens: [
          ReportScreen(
            screenId: 'g',
            title: 'H1 Garage',
            fields: [],
            isMergedGroup: true,
            phrases: [
              '[[SUBHEADING]] Garage',
              'Description: A garage.',
              '[[SUBHEADING]] Empty one',
              '[[SUBHEADING]] Garage Defects',
              'Minor defects: Cracks.',
              '[[SUBHEADING]] Empty last',
            ],
          ),
        ],
      ),
    ];
    final xml = await _xml(_doc(sections: sections));
    expect(xml, isNot(contains('[[SUBHEADING]]')));
    expect(xml, contains('<w:pStyle w:val="Heading3"/></w:pPr><w:r><w:t xml:space="preserve">Garage</w:t>'));
    expect(xml, contains('<w:pStyle w:val="Heading3"/></w:pPr><w:r><w:t xml:space="preserve">Garage Defects</w:t>'));
    expect(xml, isNot(contains('Empty one')));
    expect(xml, isNot(contains('Empty last')));
  });
}
